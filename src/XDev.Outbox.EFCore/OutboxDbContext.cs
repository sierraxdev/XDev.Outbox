using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.Extensions.Options;
using System;
using System.Data;
using System.Dynamic;
using System.Linq;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;

namespace XDev.Outbox.EFCore
{
    public abstract class OutboxDbContext<TKey> : OutboxDbContext<TKey, OutboxDbContext<TKey>>, IOutboxDbContext<TKey> where TKey : struct
    {
        public OutboxDbContext(DbContextOptions options)
            : base(options)
        {
        }
    }
    public abstract class OutboxDbContext<TKey, TContext> : DbContext where TKey : struct where TContext : DbContext, IOutboxDbContext<TKey>
    {
        public DbSet<OutboxMessage<TKey>> OutboxMessage { get; set; }

        public OutboxDbContext(DbContextOptions options)
            : base(options)
        {
        }

        protected override void OnModelCreating(ModelBuilder builder)
        {
            var outboxOptions = ((IOptions<OutboxDbContextConfiguration>)this.GetService<IServiceProvider>()?.GetService(typeof(IOptions<OutboxDbContextConfiguration>)))?.Value;
            var outboxOptions = ((IOptions<OutboxDbContextConfiguration>)(internalServiceProvider.GetService(typeof(IOptions<OutboxDbContextConfiguration>))
            builder.Entity<OutboxMessage<TKey>>(config =>
            {
                config.ToTable(outboxOptions?.TableName ?? nameof(OutboxMessage));

                config.HasKey(e => e.Id);

                config.Property(e => e.Type).HasMaxLength(200);

                config.Property(e => e.Payload)
                    .HasConversion(
                        v => JsonSerializer.Serialize(v, OutboxConfiguration.SerializerOptions),
                        v => JsonSerializer.Deserialize(v, typeof(ExpandoObject), OutboxConfiguration.SerializerOptions)
                    );

                //config.OwnsOne(e => e.Payload, b =>
                //{
                //    b.ToJson();
                //});
            });
        }

        protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder)
        {
            base.OnConfiguring(optionsBuilder);
        }

        public override async Task<int> SaveChangesAsync(CancellationToken cancellationToken = default)
        {
            var result = default(int);

            var outbox = this.GetService<IOutbox>();
            var messageQueue = this.GetService<IMessageQueue<TKey>>();
            var timeProvider = this.GetService<TimeProvider>();
            var events = outbox.GetEvents();

            if (events.Any())
            {
                var hasExistingTransaction = Database.CurrentTransaction != null;
                if (!hasExistingTransaction)
                {
                    var executionStrategy = Database.CreateExecutionStrategy();
                    result = await executionStrategy.ExecuteAsync(async () =>
                    {
                        using var transaction = await Database.BeginTransactionAsync(IsolationLevel.ReadCommitted, cancellationToken);

                        var result = await base.SaveChangesAsync(cancellationToken);

                        if (events.Any())
                        {
                            AddOutboxMessages(outbox, timeProvider);

                            Database.AutoTransactionBehavior = AutoTransactionBehavior.Never;
                            await base.SaveChangesAsync(cancellationToken);
                        }

                        await transaction.CommitAsync(cancellationToken);

                        return result;
                    });
                }
                else
                {
                    result = await base.SaveChangesAsync(cancellationToken);

                    AddOutboxMessages(outbox, timeProvider);

                    Database.AutoTransactionBehavior = AutoTransactionBehavior.Never;
                    await base.SaveChangesAsync(cancellationToken);
                }
            }
            else
            {
                result = await base.SaveChangesAsync(cancellationToken);
            }

            foreach (var item in ChangeTracker.Entries<OutboxMessage<TKey>>()
                .Where(x => x.State == EntityState.Unchanged)
                .Select(x => x.Entity)
                .Where(x => !x.LockExpiresAt.HasValue || x.LockExpiresAt.Value < timeProvider.GetUtcNow().DateTime))
            {
                await messageQueue.EnqueueAsync(item, cancellationToken);
            }

            return result;
        }

        private void AddOutboxMessages(IOutbox outbox, TimeProvider timeProvider)
        {
            var outboxOptions = this.GetService<IOptions<OutboxConfiguration>>()?.Value;

            OutboxMessage.AddRange(outbox.GetEvents().Select(x => new OutboxMessage<TKey>
            {
                Id = IsPrimaryKeyAutoGenerated(this, x) ? default : GetId(),
                Type = x.GetType().AssemblyQualifiedName,
                Payload = x,
                Created = timeProvider.GetUtcNow().DateTime,
            }));

            outbox.ClearEvents();
        }

        public string GetTableNameWithScheme<T>() where T : new()
        {
            var entityType = Model.FindEntityType(typeof(T));
            var schema = entityType.GetDefaultSchema();
            return $"{schema ?? "dbo"}.{entityType.GetTableName()}";
        }

        private static bool IsPrimaryKeyAutoGenerated<TEntity>(DbContext context, TEntity entity) where TEntity : class
        {
            // 1. Find the entity metadata structure
            var entityType = context.Model.FindEntityType(typeof(TEntity));
            if (entityType == null) return false;

            // 2. Fetch the primary key
            var primaryKey = entityType.FindPrimaryKey();
            if (primaryKey == null) return false;

            // 3. Verify if any of the key properties are generated on insert
            return primaryKey.Properties.Any(p => p.ValueGenerated == ValueGenerated.OnAdd);
        }

        private TKey GetId()
        {
            if (typeof(TKey) == typeof(string))
            {
                return (TKey)Convert.ChangeType(Guid.NewGuid().ToString(), typeof(TKey));
            }
            if (typeof(TKey) == typeof(Guid))
            {
                return (TKey)Convert.ChangeType(Guid.NewGuid(), typeof(TKey));
            }
            return default;
        }
    }
}