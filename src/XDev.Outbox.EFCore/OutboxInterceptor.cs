using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using System;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;

namespace XDev.Outbox.EFCore
{
    public class OutboxInterceptor<TKey> : SaveChangesInterceptor
        where TKey : struct
    {
        private readonly TimeProvider _timeProvider;
        private readonly IMessageQueue<TKey> _messageQueue;

        public OutboxInterceptor(
            TimeProvider timeProvider,
            IMessageQueue<TKey> messageQueue)
        {
            _timeProvider = timeProvider;
            _messageQueue = messageQueue;
        }

        public override async ValueTask<InterceptionResult<int>> SavingChangesAsync(
            DbContextEventData eventData,
            InterceptionResult<int> result,
            CancellationToken cancellationToken = default)
        {
            var dbContext = eventData.Context;

            if (dbContext is null)
            {
                return await base.SavingChangesAsync(eventData, result, cancellationToken);
            }

            var outboxContext = dbContext as IOutboxDbContext<TKey>;
            if (outboxContext is null)
                return await base.SavingChangesAsync(eventData, result, cancellationToken);

            var outbox = dbContext.GetService<IOutbox>();
            var events = outbox.GetEvents();

            if (events.Any())
            {
                outboxContext.OutboxMessage.AddRange(events.Select(x => new OutboxMessage<TKey>
                {
                    Id = IsPrimaryKeyAutoGenerated(dbContext, x) ? default : GetId(),
                    Type = x.GetType().AssemblyQualifiedName,
                    Payload = x,
                    Created = _timeProvider.GetUtcNow().DateTime,
                }));

                outbox.ClearEvents();
            }

            return await base.SavingChangesAsync(eventData, result, cancellationToken);
        }

        public override int SavedChanges(SaveChangesCompletedEventData eventData, int result)
        {
            var dbContext = eventData.Context;

            if (dbContext is null)
            {
                return base.SavedChanges(eventData, result);
            }

            foreach (var item in dbContext.ChangeTracker.Entries<OutboxMessage<TKey>>()
                .Where(x => x.State == EntityState.Unchanged)
                .Select(x => x.Entity)
                .Where(x => !x.LockExpiresAt.HasValue || x.LockExpiresAt.Value < _timeProvider.GetUtcNow().DateTime))
            {
                _messageQueue.EnqueueAsync(item).GetAwaiter().GetResult();
            }

            return base.SavedChanges(eventData, result);
        }

        public override async ValueTask<int> SavedChangesAsync(
            SaveChangesCompletedEventData eventData,
            int result,
            CancellationToken cancellationToken = default)
        {
            var dbContext = eventData.Context;

            if (dbContext is null)
            {
                return await base.SavedChangesAsync(eventData, result, cancellationToken);
            }

            foreach (var item in dbContext.ChangeTracker.Entries<OutboxMessage<TKey>>()
                .Where(x => x.State == EntityState.Unchanged)
                .Select(x => x.Entity)
                .Where(x => !x.LockExpiresAt.HasValue || x.LockExpiresAt.Value < _timeProvider.GetUtcNow().DateTime))
            {
                await _messageQueue.EnqueueAsync(item, cancellationToken);
            }

            return await base.SavedChangesAsync(eventData, result, cancellationToken);
        }

        public static bool IsPrimaryKeyAutoGenerated<TEntity>(DbContext context, TEntity entity) where TEntity : class
        {
            // 1. Find the entity metadata structure
            var entityType = context.Model.FindEntityType(typeof(TEntity));
            if (entityType == null) return false;

            // 2. Fetch the primary key
            var primaryKey = entityType.FindPrimaryKey();
            if (primaryKey == null) return false;

            // 3. Verify if any of the key properties are generated on insert
            return primaryKey.Properties.Any(p => p.ValueGenerated == ValueGenerated.OnAdd);
        }

        private TKey GetId()
        {
            if(typeof(TKey) == typeof(string))
            {
                return (TKey)Convert.ChangeType(Guid.NewGuid().ToString(), typeof(TKey));
            }
            if(typeof(TKey) == typeof(Guid))
            {
                return (TKey)Convert.ChangeType(Guid.NewGuid(), typeof(TKey));
            }
            return default;
        }
    }
}
